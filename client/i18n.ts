export type Translate = (key: string, params?: Record<string, string | number>) => string;

export interface LocaleLike {
  getLocale?: () => { active?: string };
  lang?: string;
}

export function activeLang(locale: LocaleLike | undefined | null): Lang {
  try {
    const code = locale?.getLocale?.().active ?? locale?.lang;
    return code === 'en' ? 'en' : 'zh';
  } catch {
    return 'zh';
  }
}

export function buildTranslate(locale: LocaleLike | undefined | null): Translate {
  const lang = activeLang(locale);
  return (key, params) => {
    const template = DICT[lang][key] ?? DICT.zh[key] ?? key;
    if (params === undefined) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
  };
}

/** 构建期校验：两套键集合与占位符必须一致。 */
export function checkI18n(): string[] {
  const problems: string[] = [];
  const zhKeys = Object.keys(DICT.zh);
  const enKeys = Object.keys(DICT.en);
  for (const key of zhKeys) if (!(key in DICT.en)) problems.push(`en 缺键：${key}`);
  for (const key of enKeys) if (!(key in DICT.zh)) problems.push(`zh 缺键：${key}`);
  const placeholders = (text: string): string[] => (text.match(/\{\w+\}/g) ?? []).sort();
  for (const key of zhKeys) {
    if (!(key in DICT.en)) continue;
    const a = placeholders(DICT.zh[key] ?? '').join(',');
    const b = placeholders(DICT.en[key] ?? '').join(',');
    if (a !== b) problems.push(`占位符不一致：${key}`);
  }
  return problems;
}
